package client

import (
	"context"
	"errors"
	"net/http"
	"net/url"
	"strings"
)

// corsPolicyPath returns the CORS policy endpoint scoped to a single bucket.
func corsPolicyPath(bucketName string) string {
	return "/buckets/cross-origin-resource-sharing-policies?bucket_names=" + url.QueryEscape(bucketName)
}

// corsRulePath returns the CORS rules sub-endpoint scoped to a bucket and rule name.
func corsRulePath(bucketName, ruleName string) string {
	return "/buckets/cross-origin-resource-sharing-policies/rules?bucket_names=" +
		url.QueryEscape(bucketName) + "&names=" + url.QueryEscape(ruleName)
}

// GetCorsPolicy retrieves a bucket's CORS policy (with its embedded rules) by bucket
// name. Returns an IsNotFound error if no policy exists for the bucket.
func (c *FlashBladeClient) GetCorsPolicy(ctx context.Context, bucketName string) (*CrossOriginResourceSharingPolicy, error) {
	return getOneByName[CrossOriginResourceSharingPolicy](c, ctx, corsPolicyPath(bucketName), "CORS policy", bucketName)
}

// EnsureCorsPolicy creates the CORS policy for a bucket by POSTing an EMPTY body.
// The policy name is auto-generated by the array and rules cannot be included here.
// An "already exists" response (HTTP 400/409 whose message contains "exist") is
// tolerated as a no-op so the operation is idempotent.
func (c *FlashBladeClient) EnsureCorsPolicy(ctx context.Context, bucketName string) error {
	if err := c.post(ctx, corsPolicyPath(bucketName), nil, nil); err != nil {
		if corsAlreadyExists(err) {
			return nil
		}
		return err
	}
	return nil
}

// PostCorsRule creates (or replaces) a named CORS rule on the /rules sub-endpoint.
func (c *FlashBladeClient) PostCorsRule(ctx context.Context, bucketName, ruleName string, body CorsRulePost) error {
	return c.post(ctx, corsRulePath(bucketName, ruleName), body, nil)
}

// DeleteCorsRule removes a named CORS rule. A missing rule (404 or a "does not exist"
// message) is tolerated so reconciliation is idempotent.
func (c *FlashBladeClient) DeleteCorsRule(ctx context.Context, bucketName, ruleName string) error {
	if err := c.delete(ctx, corsRulePath(bucketName, ruleName)); err != nil {
		if IsNotFound(err) || corsMissing(err) {
			return nil
		}
		return err
	}
	return nil
}

// DeleteCorsPolicy deletes the CORS policy for a bucket (removing it and its rules).
func (c *FlashBladeClient) DeleteCorsPolicy(ctx context.Context, bucketName string) error {
	return c.delete(ctx, corsPolicyPath(bucketName))
}

// corsAlreadyExists reports whether err is a FlashBlade "already exists" response for
// a CORS policy: HTTP 400 or 409 whose error message contains "exist".
func corsAlreadyExists(err error) bool {
	var apiErr *APIError
	if !errors.As(err, &apiErr) {
		return false
	}
	if apiErr.StatusCode != http.StatusBadRequest && apiErr.StatusCode != http.StatusConflict {
		return false
	}
	return corsMessageContains(apiErr, "exist")
}

// corsMissing reports whether err indicates a CORS rule/policy no longer exists.
func corsMissing(err error) bool {
	var apiErr *APIError
	if !errors.As(err, &apiErr) {
		return false
	}
	return corsMessageContains(apiErr, "does not exist") || corsMessageContains(apiErr, "not exist")
}

// corsMessageContains reports whether any error message (sub-errors or top-level)
// contains the given lowercase substring.
func corsMessageContains(apiErr *APIError, sub string) bool {
	for _, e := range apiErr.Errors {
		if strings.Contains(strings.ToLower(e.Message), sub) {
			return true
		}
	}
	return strings.Contains(strings.ToLower(apiErr.Message), sub)
}
